const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const crypto = require('node:crypto');
const { spawnSync } = require('node:child_process');
const initSqlJs = require('sql.js');
const hash = p => crypto.createHash('sha256').update(fs.readFileSync(p)).digest('hex');
(async () => {
  const SQL = await initSqlJs();
  const dir = fs.mkdtempSync(path.join(process.env.TMPDIR || os.tmpdir(), 'elwafa-copy-migration-'));
  try {
    const source = path.join(dir, 'source.sqlite');
    const backup = path.join(dir, 'backup.sqlite');
    const target = path.join(dir, 'target.sqlite');
    const restored = path.join(dir, 'restored.sqlite');
    const db = new SQL.Database();
    db.run(`CREATE TABLE admins(id TEXT PRIMARY KEY, name TEXT NOT NULL, password_hash TEXT NOT NULL, created_at TEXT NOT NULL);
      CREATE TABLE sessions(token_hash TEXT PRIMARY KEY, admin_id TEXT NOT NULL, expires_at INTEGER NOT NULL);
      CREATE TABLE inquiries(id TEXT PRIMARY KEY, name TEXT NOT NULL, phone TEXT NOT NULL, subject TEXT NOT NULL, stage TEXT NOT NULL, agent_id TEXT, due TEXT NOT NULL, updated_at TEXT NOT NULL);
      CREATE TABLE entries(id TEXT PRIMARY KEY, inquiry_id TEXT NOT NULL, author_id TEXT NOT NULL, kind TEXT NOT NULL, text TEXT NOT NULL, at TEXT NOT NULL);
      INSERT INTO admins VALUES('admin-1','SYNTHETIC','HASH_PLACEHOLDER','2026-01-01');
      INSERT INTO sessions VALUES('TOKEN_PLACEHOLDER','admin-1',1000);
      INSERT INTO inquiries VALUES('inquiry-1','SYNTHETIC','000','SYNTHETIC','baru','admin-1','','2026-01-01');
      INSERT INTO entries VALUES('entry-1','inquiry-1','admin-1','internal','SYNTHETIC','2026-01-01');`);
    fs.writeFileSync(source, Buffer.from(db.export())); db.close();
    const before = hash(source);
    const run = spawnSync(process.execPath, [path.resolve('server/local-copy-migration.mjs'), source, backup, target], {encoding:'utf8'});
    assert.equal(run.status, 0, run.stderr);
    const report = JSON.parse(run.stdout);
    assert.equal(report.backupVerified, true);
    assert.equal(report.restoreVerified, true);
    assert.deepEqual(report.counts, {admins:1, sessions:0, inquiries:1, entries:1});
    assert.equal(report.sessionsSkipped, 1);
    assert.equal(hash(source), before);
    assert.equal(hash(backup), before);
    assert.notEqual(hash(target), before);
    assert.ok(!/HASH_PLACEHOLDER|TOKEN_PLACEHOLDER/.test(run.stdout + run.stderr));
    fs.copyFileSync(backup, restored, fs.constants.COPYFILE_EXCL);
    assert.equal(hash(restored), before);
    const targetDb = new SQL.Database(fs.readFileSync(target));
    assert.equal(targetDb.exec('PRAGMA integrity_check')[0].values[0][0], 'ok');
    targetDb.close();
    const again = spawnSync(process.execPath, [path.resolve('server/local-copy-migration.mjs'), source, backup, target], {encoding:'utf8'});
    assert.notEqual(again.status, 0, 'Existing backup and target must not be overwritten');
    assert.equal(hash(source), before);
    assert.equal(hash(backup), before);
    console.log('Local copy migration fixture, backup, restore, fail-closed: PASS');
  } finally { fs.rmSync(dir, {recursive:true,force:true}); }
})().catch(error => { console.error(error); process.exitCode=1; });
